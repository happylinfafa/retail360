"""Challenge 4 local Human–AI application: compare evidence-backed retrieval modes."""
import os
from pathlib import Path

import requests
import streamlit as st

from community_rag import credentials, run_question

st.set_page_config(page_title='Retail360 Community Explorer',layout='wide')
st.title('Retail360 Community Explorer')
st.caption('Real UCI transactions · Existing Neo4j graph · Weighted Louvain communities · Local AI evidence explanation')
st.info('Research finding: on the 300-customer sample, community-only retrieval was easier to describe but performed worse than unrestricted graph retrieval on 60-day new-product overlap. Use both views and inspect the source rows.')


def story(result):
    """LLM picks evidence; exact facts and all cited rows remain under tool control."""
    evidence=result['evidence']
    if not evidence:
        return 'No source-backed explanation is available.'
    descriptions=list(dict.fromkeys(row['description'] for row in evidence if row['description']))[:12]
    if not descriptions:
        return 'Product descriptions are unavailable; inspect the transaction IDs below.'
    schema={'type':'object','additionalProperties':False,
            'properties':{'selectedIndices':{'type':'array','items':{'type':'integer'}}},
            'required':['selectedIndices']}
    messages=[{'role':'system','content':
               'You are selecting evidence examples for a retail analyst. Return JSON only. '
               'Choose 1-3 indices of the most informative observed shared-product descriptions. '
               'Do not invent products or infer personal preferences.'},
              {'role':'user','content':str(descriptions)}]
    response=requests.post('http://127.0.0.1:11434/api/chat',json={
        'model':'qwen2.5:1.5b','messages':messages,'stream':False,'format':schema,
        'options':{'temperature':0,'num_predict':120}},timeout=(5,120))
    response.raise_for_status()
    if response.json().get('done_reason')=='length':
        raise ValueError('Local model response was incomplete.')
    import json
    selected=json.loads(response.json()['message']['content'])['selectedIndices']
    if not isinstance(selected,list) or not 1 <= len(selected) <= 3 or any(
            type(i) is not int or i < 0 or i >= len(descriptions) for i in selected):
        raise ValueError('Local model selected invalid evidence.')
    selected=list(dict.fromkeys(selected))
    names=[descriptions[i] for i in selected]
    return ('Observed shared purchases include '+', '.join(names)+'. '
            'These examples were selected by the local AI from retrieved evidence. '
            'The score and source rows below were computed and retrieved, not generated by the model.')


question=st.text_input('Ask about a customer',
    value="Which customers bought similar products to customer 15719, and why?")
col_a,col_b=st.columns(2)
with col_a:
    minimum=st.slider('Minimum historical Jaccard',0.10,0.50,0.10,0.01)
with col_b:
    limit=st.slider('Maximum peers',1,10,5)
use_ai=st.checkbox('Ask the local AI to select evidence examples',value=True)
if st.button('Compare retrieval modes',type='primary'):
    try:
        private=os.environ.get('RETAIL360_NEO4J_CREDENTIALS')
        if not private:
            raise ValueError('Set RETAIL360_NEO4J_CREDENTIALS to your private JSON file.')
        with st.spinner('Retrieving two evidence paths from Neo4j…'):
            result=run_question(question,credentials(private),minimum,limit)
        if use_ai:
            with st.spinner('Local AI is selecting source-backed examples…'):
                for mode in ('global','community'):
                    try: result[mode]['story']=story(result[mode])
                    except (requests.RequestException,ValueError,KeyError) as exc:
                        result[mode]['story']='AI explanation withheld; inspect the exact graph facts and source rows.'
                        result[mode]['modelError']=str(exc)
        st.session_state['comparison']=result
    except Exception as exc:
        st.error(f'Could not complete the analysis: {exc}')

result=st.session_state.get('comparison')
if result:
    st.subheader('What the graph found')
    view=st.radio('Retrieval mode',['global','community'],horizontal=True,
        format_func=lambda m:'Original GraphRAG: all similar peers' if m=='global' else 'Community-aware GraphRAG: same Louvain group')
    selected=result[view]
    st.write(selected['answer'])
    if selected['status']!='ok':
        st.warning('No verified path at these settings. Lower the threshold or select another customer.')
    else:
        st.caption(selected['uncertainty'])
        if selected.get('story'):
            st.markdown('**Local AI evidence explanation**')
            st.write(selected['story'])
        if selected.get('modelError'):
            st.warning('The local model did not pass its response check; exact graph evidence is still available.')
        peers=selected['peers']
        target=selected['customer']
        st.markdown('**Customer relationship view**')
        nodes=[{'id':target,'x':0.15,'y':0.5,'label':'Selected customer'}]
        edges=[]
        for i,p in enumerate(peers):
            y=(i+1)/(len(peers)+1)
            nodes.append({'id':p['peer'],'x':0.78,'y':y,
                          'label':f"Jaccard {p['jaccard']:.3f}; {p['sharedProductCount']} shared products"})
            edges.append({'x':0.15,'x2':0.78,'y':0.5,'y2':y,'score':p['jaccard']})
        chart={'width':'container','height':280,'layer':[
            {'data':{'values':edges},'mark':{'type':'rule','stroke':'#146c8a','strokeWidth':2},
             'encoding':{'x':{'field':'x','type':'quantitative','scale':{'domain':[0,1]},'axis':None},
                         'x2':{'field':'x2'},'y':{'field':'y','type':'quantitative','scale':{'domain':[0,1]},'axis':None},
                         'y2':{'field':'y2'},'tooltip':[{'field':'score','title':'Jaccard'}]}},
            {'data':{'values':nodes},'mark':{'type':'circle','size':1800,'color':'#ddedf3','stroke':'#146c8a'},
             'encoding':{'x':{'field':'x','type':'quantitative','scale':{'domain':[0,1]},'axis':None},
                         'y':{'field':'y','type':'quantitative','scale':{'domain':[0,1]},'axis':None},
                         'tooltip':[{'field':'id','title':'Customer'},{'field':'label','title':'Evidence'}]}},
            {'data':{'values':nodes},'mark':{'type':'text','fontSize':13,'fontWeight':'bold'},
             'encoding':{'x':{'field':'x','type':'quantitative','scale':{'domain':[0,1]},'axis':None},
                         'y':{'field':'y','type':'quantitative','scale':{'domain':[0,1]},'axis':None},
                         'text':{'field':'id'}}}]}
        st.vega_lite_chart(chart,width='stretch')
        st.dataframe(peers,width='stretch')
        peer=st.selectbox('Inspect one peer and the transaction path',[p['peer'] for p in peers])
        rows=[row for row in selected['evidence'] if row['peer']==peer]
        st.dataframe(rows,width='stretch')
        st.caption('Evidence path: customer → purchased product ← peer, with each side’s invoice and original worksheet row. Graph edges indicate historical overlap only.')
        st.markdown('**Your review**')
        decision=st.radio('Is this explanation useful?', ['Reviewing','Accept','Reject'],horizontal=True)
        correction=st.text_input('Correction or note (optional)')
        if st.button('Save feedback for this session'):
            st.session_state['feedback']={'customer':target,'mode':view,
                                           'peer':peer,'decision':decision,'note':correction}
            st.success('Feedback saved in this browser session. It has not changed the data or model.')
        if st.session_state.get('feedback'):
            st.caption(f"Last review: {st.session_state['feedback']}")
st.divider()
st.caption('Local research prototype. The separately deployed Challenge 2 app does not contain this feature. No future purchases are used in graph construction or live retrieval.')
